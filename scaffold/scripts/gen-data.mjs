// Bake demo.config.json + manifests (shots, VO) into src/demo.mjs and src/generated.mjs (pas d'import JSON dans le bundle).
// La VO est optionnelle (demo.config.json → voiceover:false, ou manifest absent) ; les shots sont obligatoires.
import fs from 'node:fs'; import {fileURLToPath} from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const read = (p) => (fs.existsSync(root + p) ? JSON.parse(fs.readFileSync(root + p, 'utf8')) : null);
const cfg = read('demo.config.json');
if (!cfg) { console.error('missing demo.config.json'); process.exit(1); }
const shots = read('public/shots/manifest.json');
if (!shots) { console.error('missing public/shots/manifest.json — run npm run capture (ou npm run slides)'); process.exit(1); }
const vo = cfg.voiceover ? read('public/vo/manifest.json') : null;
if (cfg.voiceover && !vo) console.warn('WARN: voiceover:true mais public/vo/manifest.json absent — les plans dureront leur chorégraphie. Lance npm run vo.');
const K = 1920 / (cfg.capture?.cssWidth ?? 1600);
// Police de marque : jamais versionnée. On la prend sur la machine si elle y est, sinon repli sur Inter.
const os = await import('node:os'); const path = await import('node:path');
const fontDst = root + 'public/fonts/PPTelegraf-Bold.ttf';
if (!fs.existsSync(fontDst)) {
  const h = os.homedir();
  const candidates = [process.env.PPTELEGRAF_PATH, path.join(h, '.demo-video/fonts/PPTelegraf-Bold.ttf'), path.join(h, 'Library/Fonts/PPTelegraf-Bold.ttf'), path.join(h, 'Library/Fonts/PPTelegraf-Bold.otf'), '/Library/Fonts/PPTelegraf-Bold.ttf'].filter(Boolean);
  const found = candidates.find((p) => fs.existsSync(p));
  if (found) { fs.mkdirSync(root + 'public/fonts', {recursive: true}); fs.copyFileSync(found, fontDst); }
}
const headFont = fs.existsSync(fontDst) ? 'PPTelegraf' : 'Inter';
if (headFont === 'Inter') console.warn('INFO: PP Telegraf absente, cartons en Inter. Pour la police Zeliq, place PPTelegraf-Bold.ttf dans ~/.demo-video/fonts/.');
const lang = cfg.lang ?? 'fr';
const {capture, framewave, ...pub} = cfg; // demo.mjs n'embarque que ce dont le bundle a besoin (+ framewave.voTrack pour Clip.tsx)
pub.framewave = {voTrack: framewave?.voTrack ?? 'separate'};
pub.headFont = headFont;
fs.writeFileSync(root + 'src/demo.mjs', '// generated by scripts/gen-data.mjs from demo.config.json — do not edit\nexport const DEMO = ' + JSON.stringify(pub, null, 1) + ';\n');
fs.writeFileSync(root + 'src/generated.mjs', '// generated by scripts/gen-data.mjs — do not edit\nexport const GENERATED = {\n' +
  `  ${lang}: {dir: "shots", K: ${K}, SHOTS: ${JSON.stringify(shots)}, VO: ${JSON.stringify(vo ?? {})}},\n};\n`);
console.log('generated.mjs ok —', Object.keys(shots).length, 'shots,', Object.keys(vo ?? {}).length, 'vo tracks, K =', K.toFixed(3), '· demo.mjs ok');
